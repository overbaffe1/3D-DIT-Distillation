__device__ __constant__ int EDGE2CORNERS[12][2] = {
    {0,1},{1,2},{2,3},{3,0}, {4,5},{5,6},{6,7},{7,4}, {0,4},{1,5},{2,6},{3,7}
};

__device__ __constant__ int VORDER[8] = {2, 6, 4, 0, 3, 7, 5, 1};

__global__ void edge_face_count_kernel(
    const int N_CUBES,
    const int32_t* __restrict__ cube_vidx,
    const float* __restrict__ vsdf,
    const float isovalue,
    uint8_t* __restrict__ cube_mask,
    int32_t* __restrict__ edge_count,
    int32_t* __restrict__ face_count
) {

    const int gidx = blockIdx.x * blockDim.x + threadIdx.x;
    if (gidx >= N_CUBES) return;

    // read cube_ids per 2 instructions
    const int32_t* cube = cube_vidx + gidx * 8;
    const int4 cube0 = reinterpret_cast<const int4*>(cube)[0];
    const int4 cube1 = reinterpret_cast<const int4*>(cube)[1];
    int cube_ids[8] = {cube0.x, cube0.y, cube0.z, cube0.w, cube1.x, cube1.y, cube1.z, cube1.w};

    int vmask = 0;
#pragma unroll
    for (int i = 0; i < 8; i++)
    {
        if (vsdf[cube_ids[VORDER[i]]] < isovalue)
        {
            vmask |= 1 << i;
        }
    }
    cube_mask[gidx] = static_cast<uint8_t>(vmask);


    int emask = EDGE_TABLE[vmask];
    edge_count[gidx] = __popc(emask);

    int fcnt = 0;
    for (int i = 0; i < 15; i += 3)
    {
        if (FACE_TABLE[vmask][i] == -1) break;
        fcnt++;
    }
    face_count[gidx] = fcnt;
}

__global__ void edge_ids_kernel(
    const int N_CUBES,
    const int32_t* __restrict__ cube_vidx,
    const uint8_t* __restrict__ cube_mask,
    const int32_t* __restrict__ edge_off,
    int64_t* __restrict__ edge_idx
) {
    const int gidx = blockIdx.x * blockDim.x + threadIdx.x;
    if (gidx >= N_CUBES) return;

    // read cube_ids per 2 instructions
    const int32_t* cube = cube_vidx + gidx * 8;
    const int4 cube0 = reinterpret_cast<const int4*>(cube)[0];
    const int4 cube1 = reinterpret_cast<const int4*>(cube)[1];
    int cube_ids[8] = {cube0.x, cube0.y, cube0.z, cube0.w, cube1.x, cube1.y, cube1.z, cube1.w};

    int vmask = static_cast<int32_t>(cube_mask[gidx]);
    int emask = EDGE_TABLE[vmask];

    int estart = gidx > 0 ? edge_off[gidx - 1]: 0;

#pragma unroll
    for (int e = 0; e < 12; e++)
    {
        if (emask & (1 << e))
        {
            const int32_t i0 = cube_ids[VORDER[EDGE2CORNERS[e][0]]];
            const int32_t i1 = cube_ids[VORDER[EDGE2CORNERS[e][1]]];
            edge_idx[estart++] = (static_cast<int64_t>(min(i0, i1)) << 31) | static_cast<int64_t>(max(i0, i1));
        }
    }
}

__global__ void emit_verts_kernel(
    const int N_EDGES,
    const int64_t* __restrict__ edge_idx,
    const float3* __restrict__ vpos,
    const float* __restrict__ vsdf,
    const float isovalue,
    float3* __restrict__ verts
)
{
    const int gidx = blockIdx.x * blockDim.x + threadIdx.x;
    if (gidx >= N_EDGES) return;

    const int64_t edge = edge_idx[gidx];
    const int i0 = static_cast<int32_t>(edge >> 31), i1 = static_cast<int32_t>(edge & ((1LL << 31) - 1));

    const float3 v0 = vpos[i0], v1 = vpos[i1];
    const double sdf0 = static_cast<double>(vsdf[i0]), sdf1 = static_cast<double>(vsdf[i1]);

    const double t = fmin(fmax(fabs(sdf0 - sdf1) > 1e-12 ? (sdf0 - isovalue) / (sdf0 - sdf1) : 0.5, 0.0), 1.0);

    verts[gidx] = make_float3(
        static_cast<float>(static_cast<double>(v0.x) + t * (static_cast<double>(v1.x) - static_cast<double>(v0.x))),
        static_cast<float>(static_cast<double>(v0.y) + t * (static_cast<double>(v1.y) - static_cast<double>(v0.y))),
        static_cast<float>(static_cast<double>(v0.z) + t * (static_cast<double>(v1.z) - static_cast<double>(v0.z)))
    );
}

__global__ void emit_faces_kernel(
    const int N_CUBES,
    const uint8_t* __restrict__ cube_mask,
    const int32_t* __restrict__ edge_off,
    const int64_t* __restrict__ edge_map,
    const int32_t* __restrict__ face_off,
    int3* __restrict__ faces
)
{
    const int gidx = blockIdx.x * blockDim.x + threadIdx.x;
    if (gidx >= N_CUBES) return;

    const int32_t vmask = static_cast<int32_t>(cube_mask[gidx]);

    int emask = EDGE_TABLE[vmask];
    int estart = gidx > 0 ? edge_off[gidx - 1]: 0;

    int eids[12];
#pragma unroll
    for (int e = 0; e < 12; e++)
    {
        if (emask & (1 << e)) eids[e] = static_cast<int32_t>(edge_map[estart++]);
    }

    int fstart = gidx > 0 ? face_off[gidx - 1]: 0;

    for (int i = 0; i < 15; i += 3)
    {
        int e0 = FACE_TABLE[vmask][i + 0];
        if (e0 == -1) break;
        int e1 = FACE_TABLE[vmask][i + 1];
        int e2 = FACE_TABLE[vmask][i + 2];

        faces[fstart++] = make_int3(eids[e0], eids[e1], eids[e2]);
    }
}

std::vector<torch::Tensor> cuda_fmc_forward(torch::Tensor vpos, torch::Tensor vsdf, torch::Tensor cube_vidx, float isovalue){

    constexpr int threads = 256;
    const auto device = vpos.device();

    const int N_CUBES = cube_vidx.size(0);
    auto cube_msk = torch::empty({N_CUBES}, torch::TensorOptions().dtype(torch::kUInt8).device(device));
    auto edge_cnt = torch::empty({N_CUBES}, torch::TensorOptions().dtype(torch::kInt32).device(device));
    auto face_cnt = torch::empty({N_CUBES}, torch::TensorOptions().dtype(torch::kInt32).device(device));
    edge_face_count_kernel<<<(N_CUBES + threads - 1) / threads, threads>>>(
        N_CUBES,
        cube_vidx.data_ptr<int32_t>(), vsdf.data_ptr<float>(), isovalue,
        cube_msk.data_ptr<uint8_t>(), edge_cnt.data_ptr<int32_t>(), face_cnt.data_ptr<int32_t>()
    );

    auto active_ids = edge_cnt.nonzero();
    const int N_ACTIVE_CUBES = active_ids.size(0);
    if (N_ACTIVE_CUBES == 0) {
        return {
            torch::zeros({0, 3}, torch::TensorOptions().dtype(torch::kFloat).device(device)),
            torch::zeros({0, 3}, torch::TensorOptions().dtype(torch::kInt32).device(device)),
            torch::zeros({0}, torch::TensorOptions().dtype(torch::kInt64).device(device))
        };
    }
    cube_vidx = cube_vidx.index({active_ids}); cube_msk = cube_msk.index({active_ids});
    edge_cnt = edge_cnt.index({active_ids}); face_cnt = face_cnt.index({active_ids});

    auto edge_off = edge_cnt.cumsum_(0, torch::kInt32);
    auto face_off = face_cnt.cumsum_(0, torch::kInt32);

    auto edge_idx = torch::empty({edge_off.index({-1}).item<int32_t>()}, torch::TensorOptions().dtype(torch::kInt64).device(device));
    edge_ids_kernel<<<(N_ACTIVE_CUBES + threads - 1) / threads, threads>>>(
        N_ACTIVE_CUBES,
        cube_vidx.data_ptr<int32_t>(), cube_msk.data_ptr<uint8_t>(),
        edge_off.data_ptr<int32_t>(),  edge_idx.data_ptr<int64_t>()
    );

    std::tuple<torch::Tensor, torch::Tensor> _edge_idx = torch::_unique(edge_idx, /*sorted=*/true,/*return_inverse=*/ true);
    edge_idx = std::get<0>(_edge_idx);
    auto cube2edge = std::get<1>(_edge_idx).to(torch::kInt64);

    const int N_EDGES = edge_idx.size(0);
    auto verts = torch::empty({N_EDGES, 3}, torch::TensorOptions().dtype(torch::kFloat32).device(device));
    emit_verts_kernel<<<(N_EDGES + threads - 1) / threads, threads>>>(
        N_EDGES, edge_idx.data_ptr<int64_t>(),
        reinterpret_cast<float3*>(vpos.data_ptr<float>()), vsdf.data_ptr<float>(), isovalue,
        reinterpret_cast<float3*>(verts.data_ptr<float>())
    );

    auto faces = torch::empty({face_off.index({-1}).item<int32_t>(), 3}, torch::TensorOptions().dtype(torch::kInt32).device(device));
    emit_faces_kernel<<<(N_ACTIVE_CUBES + threads - 1) / threads, threads>>>(
        N_ACTIVE_CUBES,
        cube_msk.data_ptr<uint8_t>(),
        edge_off.data_ptr<int32_t>(), cube2edge.data_ptr<int64_t>(),
        face_off.data_ptr<int32_t>(),  reinterpret_cast<int3*>(faces.data_ptr<int32_t>())
    );


    return {verts, faces, edge_idx};
}

__global__ void fmc_backward_kernel(
    const int N_EDGES,
    const float3* __restrict__ grad_verts,
    const int64_t* __restrict__ edge_idx,
    const float3* __restrict__ vpos,
    const float* __restrict__ vsdf,
    const float isovalue,
    float* __restrict__ grad_vpos,
    float* __restrict__ grad_vsdf
){
    const int gidx = blockIdx.x * blockDim.x + threadIdx.x;
    if (gidx >= N_EDGES) return;

    const int64_t edge = edge_idx[gidx];
    const int i0 = static_cast<int32_t>(edge >> 31), i1 = static_cast<int32_t>(edge & ((1LL << 31) - 1));

    // recompute forward
    const float3 _v0 = vpos[i0], _v1 = vpos[i1];
    const double3 v0 = make_double3(static_cast<double>(_v0.x), static_cast<double>(_v0.y), static_cast<double>(_v0.z));
    const double3 v1 = make_double3(static_cast<double>(_v1.x), static_cast<double>(_v1.y), static_cast<double>(_v1.z));

    const double sdf0 = static_cast<double>(vsdf[i0]), sdf1 = static_cast<double>(vsdf[i1]);
    if (fabs(sdf0 - sdf1) <= 1e-12) return;
    const double t = fmin(fmax((sdf0 - isovalue) / (sdf0 - sdf1), 0.0), 1.0);

    const float3 _gv = grad_verts[gidx];
    const double3 gv = make_double3(static_cast<double>(_gv.x), static_cast<double>(_gv.y), static_cast<double>(_gv.z));

    // grad to v0
    atomicAdd(&grad_vpos[i0 * 3 + 0], static_cast<float>((1 - t) * gv.x));
    atomicAdd(&grad_vpos[i0 * 3 + 1], static_cast<float>((1 - t) * gv.y));
    atomicAdd(&grad_vpos[i0 * 3 + 2], static_cast<float>((1 - t) * gv.z));

    // grad to v1
    atomicAdd(&grad_vpos[i1 * 3 + 0], static_cast<float>(t * gv.x));
    atomicAdd(&grad_vpos[i1 * 3 + 1], static_cast<float>(t * gv.y));
    atomicAdd(&grad_vpos[i1 * 3 + 2], static_cast<float>(t * gv.z));

    const double alpha = gv.x * (v1.x - v0.x) + gv.y * (v1.y - v0.y) + gv.z * (v1.z - v0.z);
    atomicAdd(&grad_vsdf[i0], static_cast<float>(alpha * (1 - t) / (sdf0 - sdf1 + 1e-12)));
    atomicAdd(&grad_vsdf[i1], static_cast<float>(alpha * t / (sdf0 - sdf1 + 1e-12)));

}

std::vector<torch::Tensor> cuda_fmc_backward(
    torch::Tensor grad_verts, torch::Tensor edge_idx,
    torch::Tensor vpos, torch::Tensor vsdf, float isovalue
){

    constexpr int threads = 256;
    auto device = grad_verts.device();

    auto grad_vpos = torch::zeros_like(vpos);
    auto grad_vsdf = torch::zeros_like(vsdf);
    const int N_EDGES = edge_idx.size(0);
    fmc_backward_kernel<<<(N_EDGES + threads - 1) / threads, threads>>>(
        N_EDGES,
        reinterpret_cast<float3*>(grad_verts.data_ptr<float>()), edge_idx.data_ptr<int64_t>(),
        reinterpret_cast<float3*>(vpos.data_ptr<float>()), vsdf.data_ptr<float>(), isovalue,
        grad_vpos.data_ptr<float>(), grad_vsdf.data_ptr<float>()
    );

    return {grad_vpos, grad_vsdf};
}



